// chem_glassgen (Stage 68): every shape of the glassware table (data/glassware.json), made at build time as glass::make
// makes it, written out to the last bit for the lab to take as it is (glassware.cpp's glass::find). The same source
// and the same flags as the lab's own (native/CMakeLists.txt), so the same numbers; a test holds each to glass::make
// (test_glassware.cpp). Making them took more than half the time of a short test, and of opening the game.
//
//   chem_glassgen OUT.inc
#include "lab/glassware.hpp"
#include "lab/glassware_data.hpp"

#include <nlohmann/json.hpp>

#include <cstdio>
#include <fstream>
#include <sstream>
#include <string>

using lab::glass::Chain;
using lab::glass::Piece;
using lab::glass::Vessel;

namespace {

// (Vessel's size where this was written: a member added there is one to write here, then set its size)
template <size_t N>
struct VesselSize {
	static_assert(N == 336, "lab::glass::Vessel has changed: write its new members in shape(), then set its size");
};
[[maybe_unused]] constexpr VesselSize<sizeof(Vessel)> vessel_size{};

std::string hex(double v) {
	char buffer[64];
	std::snprintf(buffer, sizeof buffer, "%a", v);
	return buffer;
}

std::string chain(const Chain &c) {
	std::string out = "{";
	for (const Piece &p : c) {
		out += "P(" + std::string(p.arc ? "true" : "false") + ", " + hex(p.a.r) + ", " + hex(p.a.y) + ", " + hex(p.b.r) + ", " + hex(p.b.y) + ", " + hex(p.centre.r) +
				", " + hex(p.centre.y) + ", " + hex(p.radius) + ", " + hex(p.t0) + ", " + hex(p.t1) + "), ";
	}
	return out + "}";
}

std::string shape(const Vessel &v) {
	std::ostringstream o;
	o << "\t{\n\t\tVessel v;\n";
	o << "\t\tv.kind = \"" << v.kind << "\";\n";
	const auto d = [&](const char *name, double x) { o << "\t\tv." << name << " = " << hex(x) << ";\n"; };
	const auto b = [&](const char *name, bool x) { o << "\t\tv." << name << " = " << (x ? "true" : "false") << ";\n"; };
	d("nominal_ml", v.nominal_ml);
	d("diameter", v.diameter);
	d("height", v.height);
	d("wall", v.wall);
	d("floor", v.floor);
	o << "\t\tv.outside = " << chain(v.outside) << ";\n";
	o << "\t\tv.inside = " << chain(v.inside) << ";\n";
	d("pour_ml_s", v.pour_ml_s);
	d("cap_bore", v.cap_bore);
	d("burst", v.burst);
	b("screw_cap", v.screw_cap);
	d("marks_ml", v.marks_ml);
	d("marks_error", v.marks_error);
	d("tolerance_ml", v.tolerance_ml);
	d("graduation_ml", v.graduation_ml);
	d("delivery_s", v.delivery_s);
	d("tip_bore", v.tip_bore);
	d("zero", v.zero);
	b("outlet", v.outlet);
	b("mark", v.mark);
	d("stem", v.stem);
	d("cone_half_angle", v.cone_half_angle);
	d("paper_herzberg_s", v.paper_herzberg_s);
	d("paper_height", v.paper_height);
	b("syringe", v.syringe); // (Stage 79)
	d("plunger_least", v.plunger_least);
	d("plunger_most", v.plunger_most);
	d("plunger_friction", v.plunger_friction);
	d("plunger_drag", v.plunger_drag);
	d("plunger_length", v.plunger_length);
	d("handle", v.handle);
	d("clamp", v.clamp);
	o << "\t\tv.paths = {";
	for (const double x : v.paths) {
		o << hex(x) << ", ";
	}
	o << "};\n";
	d("capacity_cached", v.capacity_cached);
	o << "\t\tout.push_back(std::move(v));\n\t}\n";
	return o.str();
}

} // namespace

int main(int argc, char **argv) {
	if (argc != 2) {
		std::fprintf(stderr, "usage: chem_glassgen OUT.inc\n");
		return 2;
	}
	const nlohmann::json table = nlohmann::json::parse(lab::glass::GLASSWARE_JSON);
	std::string body;
	int count = 0;
	for (const nlohmann::json &kind : table.at("kinds")) {
		for (const nlohmann::json &size : kind.at("sizes")) {
			std::string why;
			const auto v = lab::glass::make(kind.at("name").get<std::string>(), size.at("ml").get<double>(), why);
			if (!v) {
				std::fprintf(stderr, "chem_glassgen: %s\n", why.c_str());
				return 1;
			}
			body += shape(*v);
			++count;
		}
	}
	std::string text = "// Generated by chem_glassgen from data/glassware.json (Stage 68): every shape of the table, as glass::make makes\n"
					   "// it, to the last bit. Included by glassware.cpp alone.\n"
					   "namespace {\n"
					   "inline Piece P(bool arc, double ar, double ay, double br, double by, double cr, double cy, double radius, double t0, double t1) {\n"
					   "\tPiece p;\n\tp.arc = arc;\n\tp.a = { ar, ay };\n\tp.b = { br, by };\n\tp.centre = { cr, cy };\n\tp.radius = radius;\n\tp.t0 = t0;\n\tp.t1 = t1;\n\treturn p;\n}\n"
					   "void built_shapes(std::vector<Vessel> &out) {\n" +
			body + "}\n} // namespace\n";
	// written only when it changes, so what includes it is not compiled again for nothing
	{
		std::ifstream in(argv[1], std::ios::binary);
		std::ostringstream was;
		was << in.rdbuf();
		if (in && was.str() == text) {
			return 0;
		}
	}
	std::ofstream out(argv[1], std::ios::binary);
	out << text;
	std::printf("chem_glassgen: %d shapes\n", count);
	return out ? 0 : 1;
}
